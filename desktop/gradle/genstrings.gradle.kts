// Membuat R.kt (object R { object string { const val xxx = N } }) dari
// ../app/src/main/res/values/strings.xml, supaya file UI Android yang dipakai ulang
// (stringResource(R.string.xxx)) bisa dikompilasi tanpa diubah di desktop.
//
// Dipasang dari build.gradle.kts lewat: apply(from = "gradle/genstrings.gradle.kts")
// Output: build/generated/r/com/projectzero/tapeamp32/R.kt

tasks.register("generateR") {
    group = "tapeamp32"
    description = "Generate R.string constants from the Android strings.xml"

    val stringsFile = rootDir.resolve("../app/src/main/res/values/strings.xml")
    val outFile = layout.buildDirectory.file("generated/r/com/projectzero/tapeamp32/R.kt")
    inputs.file(stringsFile)
    outputs.file(outFile)

    doLast {
        val hardKeywords = setOf(
            "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in",
            "interface", "is", "null", "object", "package", "return", "super", "this", "throw",
            "true", "try", "typealias", "typeof", "val", "var", "when", "while"
        )
        val doc = javax.xml.parsers.DocumentBuilderFactory.newInstance()
            .newDocumentBuilder()
            .parse(stringsFile)
        val nodes = doc.getElementsByTagName("string")
        val keys = ArrayList<String>()
        for (i in 0 until nodes.length) {
            val name = (nodes.item(i) as org.w3c.dom.Element).getAttribute("name")
            if (name.isNotEmpty()) keys.add(name)
        }

        val sb = StringBuilder()
        sb.appendLine("// GENERATED by Gradle task :generateR from app/src/main/res/values/strings.xml -- do not edit.")
        sb.appendLine("package com.projectzero.tapeamp32")
        sb.appendLine()
        sb.appendLine("object R {")
        sb.appendLine("    object string {")
        keys.forEachIndexed { i, key ->
            val id = key.replace('.', '_')
            val ident = if (id in hardKeywords) "`$id`" else id
            sb.appendLine("        const val $ident: Int = ${i + 1}")
        }
        sb.appendLine("    }")
        sb.appendLine("}")
        sb.appendLine()
        sb.appendLine("/** Index (id - 1) -> nama key di strings.xml. Dipakai loader string desktop. */")
        sb.appendLine("val GeneratedStringKeys: Array<String> = arrayOf(")
        keys.forEach { key -> sb.appendLine("    \"$key\",") }
        sb.appendLine(")")

        val out = outFile.get().asFile
        out.parentFile.mkdirs()
        out.writeText(sb.toString())
        println("generateR: ${keys.size} string keys -> ${out.path}")
    }
}

// Membuat BuildConfig.kt (VERSION_NAME, VERSION_CODE, APPLICATION_ID) dari app/build.gradle.kts,
// supaya layar Settings/Changelog yang memakai BuildConfig.VERSION_NAME tampil versi yang sama.
tasks.register("generateBuildConfig") {
    group = "tapeamp32"
    description = "Generate BuildConfig from app/build.gradle.kts"

    val appBuild = rootDir.resolve("../app/build.gradle.kts")
    val outFile = layout.buildDirectory.file("generated/r/com/projectzero/tapeamp32/BuildConfig.kt")
    inputs.file(appBuild)
    outputs.file(outFile)

    doLast {
        val text = appBuild.readText()
        fun grab(re: String, fallback: String) =
            Regex(re).find(text)?.groupValues?.get(1) ?: fallback
        val versionName = grab("""versionName\s*=\s*"([^"]+)"""", "0.0")
        val versionCode = grab("""versionCode\s*=\s*(\d+)""", "0")
        val appId = grab("""applicationId\s*=\s*"([^"]+)"""", "com.projectzero.tapeamp32")

        val out = outFile.get().asFile
        out.parentFile.mkdirs()
        out.writeText(
            """
            // GENERATED by Gradle task :generateBuildConfig from app/build.gradle.kts -- do not edit.
            package com.projectzero.tapeamp32

            object BuildConfig {
                const val APPLICATION_ID: String = "$appId"
                const val VERSION_NAME: String = "$versionName"
                const val VERSION_CODE: Int = $versionCode
            }
            """.trimIndent() + "\n"
        )
        println("generateBuildConfig: $appId $versionName ($versionCode)")
    }
}
